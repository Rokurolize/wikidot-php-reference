<?php
// One-off R3.3 consistency tool (disclosed; modeled on
// probe-source.php's construction and state-restricted.php's
// output): run a PREFIX of the full pipeline — the named rules, in
// full-pipeline order, under the same wiki configuration, page map,
// and page var as the full pipeline — and emit the state in the
// state driver's canonical format, with the R3.3 wire encoding.
// Rules after the prefix cannot create, remove, or mutate the
// claims of rules inside it (the token table is append-only during
// parse and no parse rule edits another rule's token options), so
// for the rules inside the prefix this state is the full
// pipeline's own record; R3.3 uses it to stand in for the nine
// full-pipeline fixture records that probe-source.php could not
// serialize (their module_body values span placeholders, which
// broke its json_encode — the same gap R3.3 Part 1 closed), after
// verifying it agrees with the pre-seeded fixtures on every case
// those fixtures do carry.
//
// Usage: php prefix-source.php Rule1,Rule2,... < cases.jsonl
error_reporting(E_ALL & ~E_DEPRECATED & ~E_WARNING);
ini_set('display_errors', 'stderr');
define('WIKIDOT_ROOT', dirname(__DIR__) . '/wikidot-root');
$root = dirname(__DIR__) . '/text-wiki';
ini_set('include_path', $root . PATH_SEPARATOR
    . dirname(__DIR__) . '/wikidot-root/lib' . PATH_SEPARATOR
    . ini_get('include_path'));
require_once dirname(__DIR__) . '/wikidot-root/lib/WDStringUtils.php';
require_once __DIR__ . '/ozone-stubs.php';
require_once $root . '/Text/Wiki.php';
require_once __DIR__ . '/wiki-config.php';
require_once __DIR__ . '/pages.php';

$GLOBALS['REF_PAGES'] = ref_page_map();
$GLOBALS['REF_EXISTING_PAGES'] = array_keys(ref_page_map());

function ref_wire_encode($v) {
    if (is_string($v)) {
        if (preg_match('//u', $v) === 1) {
            return $v;
        }
        return array('$bytes' => array_values(unpack('C*', $v)));
    }
    if (is_array($v)) {
        $out = array();
        foreach ($v as $k => $x) {
            $out[$k] = ref_wire_encode($x);
        }
        return $out;
    }
    return $v;
}

$rules = array_filter(array_map('trim', explode(',', $argv[1] ?? '')));
if (!$rules) {
    fwrite(STDERR, "usage: prefix-source.php Rule1,Rule2,...\n");
    exit(2);
}

while (($line = fgets(STDIN)) !== false) {
    $line = trim($line);
    if ($line === '') continue;
    $case = json_decode($line, true);
    $id = $case['id'] ?? '?';
    try {
        $src = str_replace("\r\n", "\n", $case['source']);
        $wiki = ref_configure_wiki(new Text_Wiki($rules));
        // R3.4 disclosed extension of this one-off tool, mirroring the
        // state driver's R3.4 changes so the prefix run can stand in
        // for the full pipeline on the NEXT family's claims: the
        // per-case page is constructed exactly as batch.php constructs
        // it (the case's "tags" array, always injected), because Iftags
        // reads the page's tags and the pre-seeded fixtures were
        // generated by a tags-honoring probe. Math's equations map is
        // document instance state, so no per-case process-static reset is
        // needed.
        $caseTags = (isset($case['tags']) && is_array($case['tags'])) ? $case['tags'] : array();
        $wiki->vars['page'] = new RefPage('', 0, $caseTags);
        $wiki->parse($src);
        $segments = array();
        $parts = preg_split('/\xFF(\d+)\xFF/',
            $wiki->source, -1, PREG_SPLIT_DELIM_CAPTURE);
        foreach ($parts as $i => $part) {
            if ($i % 2 === 1) {
                $segments[] = array('k' => (int) $part);
            } else {
                $segments[] = array('t' => $part);
            }
        }
        $out = ref_wire_encode(array('id' => $id, 'segments' => $segments,
            'tokens' => $wiki->tokens));
        $json = json_encode($out);
        if ($json === false) {
            throw new Exception('json_encode failed: ' . json_last_error_msg());
        }
        echo $json, "\n";
    } catch (ProcessException $e) {
        // R3.4 PARSE-FATAL protocol, as in state-restricted.php: the
        // record is the fatal record, matching the fixture shape.
        echo json_encode(array('id' => $id,
            'fatal' => get_class($e) . ': ' . $e->getMessage())), "\n";
    } catch (Throwable $e) {
        echo json_encode(array('id' => $id,
            'error' => get_class($e) . ': ' . $e->getMessage())), "\n";
    }
}
